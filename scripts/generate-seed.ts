// Writes supabase/seed.sql from lib/catalog.ts and lib/places.ts, plus 46 sample students.
// Run: npx tsx scripts/generate-seed.ts
// Or load the same data straight into Supabase (deletes all existing data first):
//      npx tsx --env-file=.env.local scripts/generate-seed.ts --push
import { writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";
import { CATALOG } from "../lib/catalog";
import { NICK_ADJ, NICK_ANIMALS } from "../lib/demo";
import { PLACES } from "../lib/places";

function mulberry32(a: number) {
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const q = (s: string | null) => (s === null ? "null" : `'${s.replace(/'/g, "''")}'`);
const hh = (h: number) => `${String(h).padStart(2, "0")}:00`;
const placeId = (key: string) => `(select id from places where key = ${q(key)})`;
const studentId = (nick: string) => `(select id from students where nickname = ${q(nick)})`;

const H0 = 9, H1 = 23, NH = H1 - H0;
const r = mulberry32(2026);
const pick = <T,>(a: T[]) => a[Math.floor(r() * a.length)];
const popular = ["boba", "boba", "soccer", "soccer", "running", "study", "study", "ramen", "coffee", "basketball", "board games", "pizza", "museum", "korean food", "climbing", "movie", "chess", "homework", "bakery"];

type Kind = "class" | "fixed" | "never";
const students: { nick: string; busy: (Kind | null)[][]; interests: { activity: string; min: number }[] }[] = [];
const used = new Set<string>();
for (let i = 0; i < 46; i++) {
  let nick: string;
  do nick = `${pick(NICK_ADJ)} ${pick(NICK_ANIMALS)}`; while (used.has(nick));
  used.add(nick);
  // busy[d][h]: d = 0 Monday ... 6 Sunday (converted to day_of_week below)
  const busy: (Kind | null)[][] = Array.from({ length: 7 }, () => Array(NH).fill(null));
  const pairs = [[0, 2], [1, 3], [0, 2], [1, 3], [4, 4]];
  for (let c = 0; c < 4; c++) {
    const days = pick(pairs), sh = 9 + Math.floor(r() * 9), len = 1 + (r() < 0.5 ? 1 : 0);
    for (const d of new Set(days)) for (let h = sh; h < sh + len && h < H1; h++) busy[d][h - H0] = "class";
  }
  for (let d = 0; d < 7; d++) {
    if (r() < 0.35) busy[d][0] ??= "never";
    if (r() < 0.5) { busy[d][NH - 1] ??= "never"; if (r() < 0.5) busy[d][NH - 2] ??= "never"; }
    if (d >= 5 && r() < 0.4) { const s = 10 + Math.floor(r() * 6); for (let h = s; h < s + 3; h++) busy[d][h - H0] ??= "fixed"; }
  }
  const n = 2 + (r() < 0.4 ? 1 : 0), interests: { activity: string; min: number }[] = [];
  while (interests.length < n) {
    const k = pick(popular);
    if (interests.some((t) => t.activity === k)) continue;
    const info = CATALOG.find((a) => a.name === k)!;
    interests.push({ activity: k, min: Math.min(info.max, info.minDefault + (r() < 0.3 ? 1 : 0)) });
  }
  students.push({ nick, busy, interests });
}

// Busy hours as merged runs: d = 0 Monday in the generator, day_of_week 0 = Sunday in the DB
type BlockRow = { nick: string; kind: Kind; day: number; start: string; end: string };
const blocks: BlockRow[] = [];
for (const s of students) {
  s.busy.forEach((row, d) => {
    let h = 0;
    while (h < NH) {
      const kind = row[h];
      if (!kind) { h++; continue; }
      let e = h;
      while (e < NH && row[e] === kind) e++;
      blocks.push({ nick: s.nick, kind, day: (d + 1) % 7, start: hh(H0 + h), end: hh(H0 + e) });
      h = e;
    }
  });
}
const goodFor = (key: string, campus: boolean) => (campus ? CATALOG.filter((a) => a.meet === key).map((a) => a.name) : []);

const out: string[] = [];
out.push(`-- nado sample data v4 (generated by scripts/generate-seed.ts, don't edit by hand)
-- Run after schema.sql: SQL Editor > New query > paste > Run
-- Re-running deletes all data, including rooms and real students' profiles.

truncate room_members, rooms, activity_slots, interests, busy_blocks, activities, students, places cascade;
update app_clock set base = null, set_at = now(), label = null;
`);
out.push("-- Meeting spots. good_for = activities that meet there (open-rooms picks the meeting spot from it)");
out.push("insert into places (key, name, address, is_campus, good_for) values");
out.push(PLACES.map((p) => `  (${q(p.key)}, ${q(p.name)}, ${q(p.address)}, ${p.campus}, array[${goodFor(p.key, p.campus).map(q).join(", ")}]::text[])`).join(",\n") + ";\n");
out.push("-- Built-in interests (max size set by the AI)");
out.push("insert into activities (name, label, category, max_size, min_default, meet_place_id, dest_place_id, by_ai) values");
out.push(CATALOG.map((a) => `  (${q(a.name)}, ${q(a.label)}, ${q(a.category)}, ${a.max}, ${a.minDefault}, ${placeId(a.meet)}, ${placeId(a.dest)}, true)`).join(",\n") + ";\n");
out.push(`-- ${students.length} sample students`);
out.push("insert into students (nickname, is_sample) values");
out.push(students.map((s) => `  (${q(s.nick)}, true)`).join(",\n") + ";\n");
out.push("-- Busy hours (every week). Everything else from 9 AM to 11 PM is free");
out.push("insert into busy_blocks (student_id, kind, day_of_week, start_time, end_time) values");
out.push(blocks.map((b) => `  (${studentId(b.nick)}, '${b.kind}', ${b.day}, '${b.start}', '${b.end}')`).join(",\n") + ";\n");
out.push("-- Interests + the smallest group each student enjoys");
out.push("insert into interests (student_id, activity, min_size) values");
out.push(students.flatMap((s) => s.interests.map((t) => `  (${studentId(s.nick)}, ${q(t.activity)}, ${t.min})`)).join(",\n") + ";\n");

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), out.join("\n"));
console.log(`seed.sql: ${PLACES.length} places, ${CATALOG.length} activities, ${students.length} students, ${blocks.length} busy blocks`);

if (process.argv.includes("--push")) push().catch((e) => { console.error(e.message); process.exit(1); });

async function push() {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL, key = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  if (!url || !key) throw new Error("Run with --env-file=.env.local");
  const sb = createClient(url, key);
  const ok = <T,>(r: { data: T; error: { message: string } | null }, what: string) => {
    if (r.error) throw new Error(`${what}: ${r.error.message}`);
    return r.data;
  };
  // Same as the SQL truncate (children first)
  for (const t of ["room_members", "rooms", "activity_slots", "interests", "busy_blocks", "activities"] as const) {
    ok(await sb.from(t).delete().not(t === "activities" ? "name" : t === "room_members" ? "room_id" : t === "interests" ? "student_id" : "id", "is", null), `clear ${t}`);
  }
  ok(await sb.from("students").delete().not("id", "is", null), "clear students");
  ok(await sb.from("places").delete().not("id", "is", null), "clear places");
  ok(await sb.from("app_clock").update({ base: null, set_at: new Date().toISOString(), label: null }).eq("id", 1), "reset clock");

  const places = ok(await sb.from("places").insert(PLACES.map((p) => ({ key: p.key, name: p.name, address: p.address, is_campus: p.campus, good_for: goodFor(p.key, p.campus) }))).select("id, key"), "places")!;
  const pid = (k: string) => places.find((p) => p.key === k)!.id;
  ok(await sb.from("activities").insert(CATALOG.map((a) => ({ name: a.name, label: a.label, category: a.category, max_size: a.max, min_default: a.minDefault, meet_place_id: pid(a.meet), dest_place_id: pid(a.dest), by_ai: true }))), "activities");
  const made = ok(await sb.from("students").insert(students.map((s) => ({ nickname: s.nick, is_sample: true }))).select("id, nickname"), "students")!;
  const sid = (n: string) => made.find((s) => s.nickname === n)!.id;
  ok(await sb.from("busy_blocks").insert(blocks.map((b) => ({ student_id: sid(b.nick), kind: b.kind, day_of_week: b.day, start_time: b.start, end_time: b.end }))), "busy_blocks");
  ok(await sb.from("interests").insert(students.flatMap((s) => s.interests.map((t) => ({ student_id: sid(s.nick), activity: t.activity, min_size: t.min })))), "interests");
  console.log("Pushed to Supabase.");
}
